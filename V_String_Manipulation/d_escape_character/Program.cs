namespace d_escape_character;

class Program
{
    static void Main(string[] args)
    {
        // escape characters
        // 1. this will print "Nepal" in the next line.
        Console.WriteLine("Hello\nNepal");

        // 2. this will privide a tab between the words.
        Console.WriteLine("Hello\tKathmandu");

        // 3. lets you to print something with double quote
        Console.WriteLine("\"Hello Nepal\"");

        // 4. to print path using slash
        Console.WriteLine("D:\\C#\\");
    }
}
